/** 콘텐츠 생성 메시지. 컨텍스트 조립기가 만든 것을 그대로 쓴다. */
export function contentUserMessage(ctx: TopicContext): string {
  return contextToMessage(ctx)
}

/**
 * 채점 메시지 — 계획 하나를 통째로 담는다.
 *
 * ★ 루브릭(expected_points)이 들어가는 것이 핵심이다. 이게 없으면 모델이
 * 매번 기준을 새로 지어내고, 같은 답에 어제는 80점 오늘은 55점이 나온다.
 *
 * 지문 본문은 넣지 않는다. 루브릭이 이미 기준이므로 넣어봤자 입력 토큰만
 * 늘어난다. 힌트도 넣지 않는다 — 채점과 무관하다.
 */
export interface GradeTarget {
  topicId: string
  title: string
  goal: string
  material: StudyMaterial
  answers: Record<string, string>
}

export function gradeUserMessage(targets: GradeTarget[]): string {
  const blocks = targets.map((t) => {
    const questions = t.material.questions.map((q) => [
      `  [${q.id}] ${q.prompt}`,
      `  채점 포인트:`,
      ...q.expected_points.map((p, i) => `    ${i + 1}. ${p}`),
      `  학습자 답안:`,
      `    ${t.answers[q.id]?.trim() || '(답을 쓰지 않음)'}`,
    ].join('\n'))

    return [
      `### topic_id: ${t.topicId}`,
      `주제: ${t.title}`,
      `학습 목표: ${t.goal}`,
      '',
      ...questions,
    ].join('\n')
  })

  return [
    `아래 ${targets.length}개 주제를 각각 채점해라.`,
    `응답의 topic_id 는 여기 적힌 문자열을 그대로 써라.`,
    '',
    ...blocks,
  ].join('\n\n')
}
